_REST = {"heavy": (135, "2'30-3'"), "guided": (100, "1'30-2'"), "timed": (110, "2'")}

def _rest(e):
    if e["unit"] in ("s", "s/côté", "temps"): return _REST["timed"]
    if e["kind"] == "Poids libre" and not _ISO.search(e["name"]): return _REST["heavy"]
    return _REST["guided"]

def adapt_exercise(e):
    """Retourne une copie adaptée + raison (None si inchangé)."""
    x = dict(e); x["adapted"] = False; x["why"] = ""; x["orig"] = None
    if e["unit"] in ("reps", "reps/jambe") and re.fullmatch(r"\d+(-\d+)?", e["reps"]):
        for rx, new, why in _REPS_ADAPT:
            if re.search(rx, e["name"], re.I):
                x["orig"] = f'{e["sets"]}×{e["reps"]}'
                if new: x["reps"] = new
                if re.search("nordic|glute ham", e["name"], re.I): x["sets"] = min(x["sets"], 3); x["reps"] = "3-5"
                x["adapted"] = True; x["why"] = why; break
    if re.search("dips", e["name"], re.I):
        x["note"] = (x["note"] + " " if x["note"] else "") + "Descends jusqu'à ~90° de flexion de coude, pas plus (protège l'épaule)."
        if not x["adapted"]: x["adapted"] = True; x["orig"] = f'{e["sets"]}×{e["reps"]}'; x["why"] = "Amplitude limitée à 90° de coude pour protéger l'épaule."
    s, label = _rest(x); x["rest_s"] = s; x["rest"] = label
    return x

def scale_sets(i, base, faf):
    """Modulation du volume par le FAF (0,5–1,15)."""
    if faf >= 0.95: return base
    if faf >= 0.80: return base if i < 2 else max(2, base - 1)
    if faf >= 0.65: return min(base, 3) if i < 2 else 2
    return 2 if i < 3 else 0

def effort_note(faf):
    if faf >= 0.95: return "Forme bonne : séance complète, charges de travail habituelles (1-2 reps en réserve)."
    if faf >= 0.80: return "Forme correcte : exercices principaux complets, volume réduit sur les accessoires (-1 série)."
    if faf >= 0.65: return "Forme moyenne : 3 séries sur les 2 premiers exercices, 2 sur les autres, charges -5 à -10 %."
    return "Forme dégradée : séance courte (3 exercices × 2 séries), charges -10 à -15 %, pas d'échec musculaire."

def _find(t, n):
    for s in PROGRAM:
        if s["type"] == t and s["n"] == n: return s
    raise KeyError((t, n))

def render_session(s, faf=1.0):
    ex, dropped = [], []
    for i, e in enumerate(s["ex"]):
        a = adapt_exercise(e); k = scale_sets(i, a["sets"], faf)
        if k <= 0: dropped.append(a["name"]); continue
        if k != a["sets"]:
            a["sr"] = f'{a["sets"]}→{k}'; a["sets"] = k
        else: a["sr"] = ""
        a["i"] = len(ex) + 1; ex.append(a)
    secs = sum(x["sets"] * (35 + x["rest_s"]) for x in ex)
    return {"id": f'{s["type"]}{s["n"]:02d}', "type": s["type"], "n": s["n"], "title": s["title"], "cat": s["cat"],
            "ex": ex, "min": round(10 + secs / 60), "dropped": dropped, "effort": effort_note(faf),
            "notes": [x["why"] for x in ex if x["why"]]}

def render_program(faf=1.0):
    out = {}
    for t in ORDER:
        out[t] = {"label": TYPES[t][0], "sub": TYPES[t][1],
                  "warmup": {"title": WARMUP["title"], "phases": [p.replace("{act}", WARMUP["act"][t]) for p in WARMUP["phases"]]},
                  "sessions": [render_session(_find(t, n), faf) for n in range(1, 11)]}
    return out

_STR = {"push": re.compile(r"push|pecs?|pectoraux|développé|epaule|épaule|triceps", re.I),
        "pull": re.compile(r"pull|dos\b|traction|biceps|tirage", re.I),
        "legs": re.compile(r"leg|jambe|squat|fente|quadri|fessier|presse", re.I)}
def type_from_name(name):
    for t in ORDER:
        if _STR[t].search(name or ""): return t
    return None

LEVELS = [(0.95, "Plein régime"), (0.80, "Normal"), (0.65, "Allégé"), (0.0, "Léger")]

def level_of(faf):
    return next(lab for lim, lab in LEVELS if faf >= lim)

def today_index(day, t):
    """N° (1-10) de la séance proposée pour ce type : avance de 1 à chaque jour, décalage fixe par type.
    Sur 10 jours on parcourt les 10 séances du type, jamais deux jours de suite la même."""
    off = int(hashlib.md5(("ppl." + t).encode()).hexdigest(), 16) % 10
    return (day.toordinal() + off) % 10 + 1

def muscu_payload(day, per_type, default_type, reason):
    """per_type : {type: {"faf": float, "why": [str]}} -> charge utile complète pour le dashboard.
    Chaque type contient ses 10 séances adaptées à SON facteur de forme (jambes allégées après une grosse sortie vélo,
    haut du corps allégé après une grosse natation, etc.)."""
    types = {}
    for t in ORDER:
        faf = per_type[t]["faf"]
        sessions = [render_session(_find(t, n), faf) for n in range(1, 11)]
        types[t] = {"label": TYPES[t][0], "sub": TYPES[t][1], "faf": round(faf, 2), "level": level_of(faf),
                    "why": per_type[t]["why"], "effort": effort_note(faf), "today_n": today_index(day, t),
                    "warmup": {"title": WARMUP["title"], "phases": [p.replace("{act}", WARMUP["act"][t]) for p in WARMUP["phases"]]},
                    "sessions": sessions}
    return {"default": default_type, "reason": reason, "guide": GUIDE, "types": types}
